#!/bin/sh
# Sends the formula package.sh wrote to the Homebrew tap, as a pull request
# that merges itself once the tap's own check passes. Nothing can be pushed
# to the tap directly: its check lets through a plain version bump whose
# files download from the release and match their checksums, and nothing
# else. So publish the release first; until its files are up, the check
# fails.
#
# Usage: tap.sh
#
# A formula that changes anything besides the version and the checksums is
# refused by that check, and its pull request waits for the tap's owner.
set -eu
cd "$(dirname "$0")/../.."

tap="${GANTRY_TAP:-ultradotdev/homebrew-tap}"
formula="$PWD/dist/gantry.rb"
[ -f "$formula" ] || { echo "There is no dist/gantry.rb. Run tools/release/package.sh first." >&2; exit 1; }
version="$(sed -n 's/^  version "\(.*\)"$/\1/p' "$formula")"
[ -n "$version" ] || { echo "could not read the version from dist/gantry.rb" >&2; exit 1; }
# The tap is public, so its commits carry the same name as this project's.
name="$(git config user.name)"
email="$(git config user.email)"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
gh repo clone "$tap" "$work/tap" -- --quiet --depth 1
cd "$work/tap"
cp "$formula" Formula/gantry.rb
if git diff --quiet; then
  echo "The tap already has gantry $version."
  exit 0
fi
branch="gantry-$version"
git checkout --quiet -b "$branch"
git -c user.name="$name" -c user.email="$email" commit --quiet --all --message "gantry $version"
git push --quiet origin "$branch"
url="$(gh pr create --repo "$tap" --base main --head "$branch" --title "gantry $version" \
  --body "Generated by tools/release/package.sh from the checksums of the v$version release.")"
gh pr merge "$url" --auto --squash
echo "Opened $url. It merges by itself when the tap's check passes."
